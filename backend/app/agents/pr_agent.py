import httpx
import json
import logging
import time
from typing import Optional

from app.integrations.github import (
    get_installation_token,
    get_default_branch,
    get_latest_commit_sha,
    create_branch,
    commit_file,
    create_pr,
)
from app.db import async_session_factory
from app.models.db_models import GitHubConnection, _normalize_repo_identifier

logger = logging.getLogger(__name__)


async def open_fix_pr(
    repo_identifier: str,
    verified_fixes: list[dict],
    repo_path: str,
) -> Optional[dict]:
    async with async_session_factory() as session:
        from sqlalchemy import select
        result = await session.execute(
            select(GitHubConnection).where(GitHubConnection.repo_identifier == repo_identifier)
        )
        conn = result.scalar_one_or_none()

    if not conn:
        logger.error("No GitHub connection for %s", repo_identifier)
        return None

    owner, repo = conn.github_repo_full_name.split("/")
    token = await get_installation_token(conn.installation_id)
    if not token:
        return None

    default_branch = await get_default_branch(owner, repo, token)
    if not default_branch:
        return None

    latest_sha = await get_latest_commit_sha(owner, repo, default_branch, token)
    if not latest_sha:
        return None

    branch_name = f"codeatlas-fix-{int(time.time())}"
    if not await create_branch(owner, repo, branch_name, latest_sha, token):
        return None

    pr_title = "Auto-fix: Code quality improvements"
    pr_body_parts = ["## CodeAtlas Auto-Fix\n\nThis PR was automatically generated by CodeAtlas.\n"]

    for i, fix in enumerate(verified_fixes):
        file_path = fix.get("file_path", "")
        patched = fix.get("patched_content", "")
        description = fix.get("description", "Code quality fix")

        import os
        full_path = os.path.join(repo_path, file_path)

        existing_sha = None
        try:
            async with httpx.AsyncClient() as client:
                resp = await client.get(
                    f"https://api.github.com/repos/{owner}/{repo}/contents/{file_path}?ref={branch_name}",
                    headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github.v3+json"},
                )
                if resp.status_code == 200:
                    existing_sha = resp.json().get("sha")
        except Exception:
            pass

        commit_msg = f"fix: {description[:72]}"
        sha_result = await commit_file(
            owner, repo, branch_name, file_path,
            patched, commit_msg, token, sha=existing_sha,
        )
        if sha_result:
            pr_body_parts.append(f"- **{file_path}**: {description} ({fix.get('issue_id', '')})")

    import httpx
    pr_body = "\n".join(pr_body_parts)
    pr_body += "\n\n---\n*Generated by [CodeAtlas](https://codeatlas.app)*"

    pr_result = await create_pr(
        owner, repo, pr_title, pr_body,
        branch_name, default_branch, token,
    )

    if pr_result:
        async with async_session_factory() as session:
            from app.models.db_models import AutoFixPR
            from sqlalchemy import select
            existing = await session.execute(
                select(AutoFixPR).where(
                    AutoFixPR.repo_identifier == repo_identifier,
                    AutoFixPR.pr_number == pr_result["number"],
                )
            )
            if not existing.scalar_one_or_none():
                session.add(AutoFixPR(
                    repo_identifier=repo_identifier,
                    pr_url=pr_result["url"],
                    pr_number=pr_result["number"],
                    issues_fixed_json=json.dumps(verified_fixes),
                ))
                await session.commit()

    return pr_result
